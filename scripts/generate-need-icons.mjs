import { promises as fs } from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const needsDir = path.join(rootDir, 'needs');
const iconsDir = path.join(rootDir, 'icons', 'needs');
const cssOutputPath = path.join(rootDir, 'styles', 'needs-magnet-icons.css');

const palette = [
  '#0A2C1C',
  '#0B3B27',
  '#13633F',
  '#1F8757',
  '#2A9F69',
  '#49B982',
  '#63D89D',
  '#9CE4BF',
];

function hashSlug(slug) {
  let hash = 0;
  for (const ch of slug) {
    hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  }
  return hash >>> 0;
}

function mulberry32(seed) {
  let value = seed || 0;
  return () => {
    value |= 0;
    value = (value + 0x6D2B79F5) | 0;
    let t = Math.imul(value ^ (value >>> 15), 1 | value);
    t ^= t + Math.imul(t ^ (t >>> 7), 61 | t);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function randomInt(random, min, max) {
  return min + Math.floor(random() * (max - min + 1));
}

function mirrorWrite(grid, x, y, width, height, color) {
  const size = grid.length;
  for (let dy = 0; dy < height; dy += 1) {
    for (let dx = 0; dx < width; dx += 1) {
      const leftX = x + dx;
      const rightX = size - 1 - leftX;
      grid[y + dy][leftX] = color;
      grid[y + dy][rightX] = color;
    }
  }
}

function buildGrid(slug) {
  const random = mulberry32(hashSlug(slug));
  const gridSize = 16;
  const grid = Array.from({ length: gridSize }, () => Array(gridSize).fill(null));

  const stemHeight = randomInt(random, 4, 7);
  const startY = randomInt(random, 3, gridSize - stemHeight - 3);
  const stemColor = palette[randomInt(random, 2, 5)];
  mirrorWrite(grid, 7, startY, 2, stemHeight, stemColor);

  const capColor = palette[randomInt(random, 4, 7)];
  mirrorWrite(grid, 6, Math.max(1, startY - 1), 4, 2, capColor);

  const baseWidth = randomInt(random, 4, 6);
  const baseColor = palette[randomInt(random, 0, 3)];
  mirrorWrite(grid, Math.floor((8 - baseWidth) / 2), gridSize - 3, baseWidth, 3, baseColor);

  const accents = randomInt(random, 4, 8);
  const accentColor = palette[randomInt(random, 3, 7)];
  for (let i = 0; i < accents; i += 1) {
    const width = randomInt(random, 1, 2);
    const height = randomInt(random, 1, 2);
    const x = randomInt(random, 1, Math.floor(gridSize / 2) - width - 1);
    const y = randomInt(random, 1, gridSize - height - 1);
    mirrorWrite(grid, x + 4, y, width, height, accentColor);
  }

  const haloColor = palette[randomInt(random, 5, palette.length - 1)];
  mirrorWrite(grid, 5, Math.max(0, startY - 2), 6, 1, haloColor);
  mirrorWrite(grid, 6, Math.min(gridSize - 1, startY + stemHeight), 4, 1, haloColor);

  return grid;
}

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function readNeedSlugs() {
  const entries = await fs.readdir(needsDir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => name !== 'index.html')
    .sort((a, b) => a.localeCompare(b));
}

function gridToRects(grid) {
  const cell = 2;
  const rects = [];

  for (let y = 0; y < grid.length; y += 1) {
    let x = 0;
    while (x < grid[y].length) {
      const color = grid[y][x];
      if (!color) {
        x += 1;
        continue;
      }

      let x2 = x + 1;
      while (x2 < grid[y].length && grid[y][x2] === color) {
        x2 += 1;
      }

      rects.push({
        x: x * cell,
        y: y * cell,
        width: (x2 - x) * cell,
        height: cell,
        color,
      });
      x = x2;
    }
  }

  return rects;
}

function iconMarkup(slug) {
  const grid = buildGrid(slug);
  const rects = gridToRects(grid);
  const rectMarkup = rects
    .map((rect) => `<rect x="${rect.x}" y="${rect.y}" width="${rect.width}" height="${rect.height}" fill="${rect.color}"/>`)
    .join('\n  ');

  return `<svg width="64" height="64" viewBox="0 0 32 32" fill="none" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">\n  ${rectMarkup}\n</svg>`;
}

function colorForSlug(slug) {
  const random = mulberry32(hashSlug(slug));
  return palette[randomInt(random, 2, palette.length - 1)];
}

async function writeIcons(slugs) {
  await ensureDir(iconsDir);
  await Promise.all(slugs.map(async (slug) => {
    const markup = iconMarkup(slug);
    const iconPath = path.join(iconsDir, `${slug}.svg`);
    await fs.writeFile(iconPath, markup, 'utf8');
  }));
}

async function writeCss(slugs) {
  const baseRule = ".magnet[data-magnet-id^='needs-'],\nmain[data-need-slug] {\n  --need-icon: none;\n  --need-icon-visible: 0;\n  --need-icon-color: #000;\n}\n\n";
  const rules = slugs
    .map((slug) => `.magnet[data-magnet-id='needs-${slug}'],\nmain[data-need-slug='${slug}'] {\n  --need-icon: url('icons/needs/${slug}.svg');\n  --need-icon-visible: 1;\n  --need-icon-color: ${colorForSlug(slug)};\n}\n`)
    .join('\n');
  const css = `/* Auto-generated by scripts/generate-need-icons.mjs */\n${baseRule}${rules}`;
  await fs.writeFile(cssOutputPath, css, 'utf8');
}

async function main() {
  const slugs = await readNeedSlugs();
  await writeIcons(slugs);
  await writeCss(slugs);
  console.log(`Generated ${slugs.length} need icons.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
