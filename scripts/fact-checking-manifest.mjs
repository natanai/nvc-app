import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = join(__dirname, '..');
const manifestPath = join(rootDir, 'fact-checking', '.source-manifest.json');

const SOURCE_FILES = [
  'data/Needs.csv',
  'data/Feelings.csv',
  'data/Faux Feelings.csv',
  'data/Strategies.csv',
  'data/color-palettes.csv',
  '_evidence/citations.csv',
  'data/reverse-inference.json',
  'data/observation_taxonomy.json',
  'data/observation_lexicon.json',
  'data/observation_need_templates.json',
  'data/observation_module_blueprints.json',
  'data/observation_detector_stats.json',
  'data/observation-guide.json',
];

function hashFile(relativePath) {
  const bytes = readFileSync(join(rootDir, relativePath));
  return createHash('sha256').update(bytes).digest('hex');
}

function currentHashes() {
  return Object.fromEntries(SOURCE_FILES.map((relativePath) => [relativePath, hashFile(relativePath)]));
}

function writeManifest() {
  const payload = {
    version: 1,
    note: 'Generated by scripts/fact-checking-manifest.mjs. Refresh the fact-checking export before importing if any source hash changes.',
    sources: currentHashes(),
  };
  writeFileSync(manifestPath, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`Wrote ${SOURCE_FILES.length} fact-checking source hashes.`);
}

function checkManifest() {
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  } catch (error) {
    throw new Error(
      'fact-checking/.source-manifest.json is missing or invalid. Run the Fact-Checking Spreadsheets export workflow before importing.',
      { cause: error },
    );
  }

  if (manifest?.version !== 1 || !manifest.sources || typeof manifest.sources !== 'object') {
    throw new Error('Unsupported fact-checking source manifest. Refresh the export before importing.');
  }

  const stale = [];
  for (const relativePath of SOURCE_FILES) {
    const expected = manifest.sources[relativePath];
    const current = hashFile(relativePath);
    if (!expected || expected !== current) stale.push(relativePath);
  }

  if (stale.length) {
    throw new Error(
      `Fact-checking export is stale relative to current canonical sources:\n- ${stale.join('\n- ')}\n` +
        'Refresh the fact-checking export, reapply the intended spreadsheet edits to that fresh export, then import again.',
    );
  }

  console.log(`Fact-checking export is fresh against ${SOURCE_FILES.length} canonical sources.`);
}

const mode = String(process.argv[2] || '').trim().toLowerCase();
if (mode === 'write') {
  writeManifest();
} else if (mode === 'check') {
  checkManifest();
} else {
  throw new Error('Usage: node scripts/fact-checking-manifest.mjs <write|check>');
}
